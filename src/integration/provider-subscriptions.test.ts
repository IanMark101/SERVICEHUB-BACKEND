import assert from 'node:assert/strict';
import test from 'node:test';
import { prisma } from '../lib/prisma';
import { env } from '../config/env';
import { startSubscriptionCheckout, reconcileSubscriptionPayment, cancelProviderSubscription, cancelSubscriptionCheckout, getProviderSubscription, adminSubscriptionOverview } from '../services/subscriptions.service';
import { createService, toggleServiceAvailability } from '../services/services.service';
import { CreateServiceSchema } from '../schema/services.schema';
import { initiateOnlinePayment } from '../services/payment-attempt.service';
import { getProviderPaymentRecords } from '../services/provider-payment-records.service';
import { getAccountDeletionEligibility } from '../services/account-deletion.service';

test('subscription payments, fee snapshots, concurrent capacity and expiry use real isolated records', async t => {
  assert.match(new URL(env.DATABASE_URL).searchParams.get('schema') || '', /^servicehub_migration_test_/);
  t.after(async () => { await prisma.$disconnect(); });
  const suffix = Date.now().toString();
  const user = (name: string) => prisma.user.create({ data: { name, email: `${name}-${suffix}@example.test`, passwordHash: 'fixture-only', phone: '09123456789', gcashNumber: '09123456789', location: 'Cordova', emailVerified: true, verificationStatus: 'APPROVED' } });
  const provider = await user('subscriptionprovider');
  const customer = await user('subscriptioncustomer');
  const other = await user('subscriptionother');
  assert.equal(provider.subscriptionPlan, 'FREE');
  const category = await prisma.category.create({ data: { name: `Subscription Fixture ${suffix}` } });
  const input = (i: number) => CreateServiceSchema.parse({ categoryId: category.id, title: `Laptop repair service ${i}`, description: 'Laptop diagnosis and repair for home and school use.', price: 1000, priceType: 'FIXED', estimatedDurationMins: 60, serviceLocationMode: 'REMOTE', paymentMethods: { gcash: true, cash: true } });
  const results = await Promise.allSettled([1, 2, 3, 4].map(i => createService(provider.id, input(i))));
  assert.equal(results.filter(result => result.status === 'fulfilled').length, 3, 'Concurrent Free creation cannot exceed three');
  const listings = await prisma.service.findMany({ where: { providerId: provider.id } });
  const initialFetch = globalThis.fetch;
  const initialSecret = env.PAYMONGO_SECRET_KEY;
  const initialPublic = env.PAYMONGO_PUBLIC_KEY;
  const initialWebhook = env.PAYMONGO_WEBHOOK_SECRET;
  env.PAYMONGO_SECRET_KEY = 'sk_test_subscription_fixture'; env.PAYMONGO_PUBLIC_KEY = 'pk_test_subscription_fixture'; env.PAYMONGO_WEBHOOK_SECRET = 'subscription_webhook_fixture';
  const intents = new Map<string, any>(); const idempotency = new Map<string, string>(); let sequence = 0;
  globalThis.fetch = (async (url: any, options: any = {}) => {
    assert.ok(String(url).startsWith('https://api.paymongo.com/v1/'), 'No external services');
    if (String(url).endsWith('/payment_intents') && options.method === 'POST') {
      const key = options.headers['Idempotency-Key'];
      const id = idempotency.get(key) ?? `pi_sub${++sequence}`;
      if (!intents.has(id)) intents.set(id, { ...JSON.parse(options.body).data.attributes, status: 'awaiting_payment_method', client_key: `secret_${id}` });
      idempotency.set(key, id);
      return Response.json({ data: { id, attributes: intents.get(id) } });
    }
    if (String(url).endsWith('/payment_methods')) return Response.json({ data: { id: 'pm_fixture' } });
    if (String(url).endsWith('/attach')) {
      const intent = intents.get(String(url).split('/').at(-2)!);
      intent.status = 'awaiting_next_action'; intent.next_action = { type: 'redirect', redirect: { url: 'https://test-sources.paymongo.com/subscription-fixture' } };
      return Response.json({ data: { attributes: intent } });
    }
    const id = String(url).split('/').at(-1)!;
    assert.ok(intents.has(id));
    return Response.json({ data: { id, attributes: intents.get(id) } });
  }) as typeof fetch;
  t.after(() => { globalThis.fetch = initialFetch; env.PAYMONGO_SECRET_KEY = initialSecret; env.PAYMONGO_PUBLIC_KEY = initialPublic; env.PAYMONGO_WEBHOOK_SECRET = initialWebhook; });
  const paid = (id: string) => { const intent = intents.get(id); intent.status = 'succeeded'; intent.payments = [{ id: `pay_${id}` }]; };

  const freeAttempt = await initiateOnlinePayment({ seekerId: customer.id, serviceId: listings[0]!.id, paymentMethod: 'gcash', serviceLocationMode: 'REMOTE' });
  assert.equal(freeAttempt.commissionRateBps, 1000);
  assert.equal(Number(freeAttempt.platformFeeAmount), 100);
  assert.ok((await getProviderPaymentRecords(prisma, provider.id, { page: 1, limit: 10, status: 'all' })).summary, 'Free analytics remain accessible');
  const checkout = await startSubscriptionCheckout(provider.id);
  const reused = await startSubscriptionCheckout(provider.id);
  assert.equal(reused.id, checkout.id, 'Repeated clicks reuse one pending subscription checkout');
  assert.equal((await getProviderSubscription(provider.id)).plan, 'FREE', 'Clicking Upgrade is not payment');
  await assert.rejects(reconcileSubscriptionPayment(other.id, checkout.paymentIntentId!), /not found/);
  paid(checkout.paymentIntentId!);
  const metadata = intents.get(checkout.paymentIntentId!).metadata;
  intents.get(checkout.paymentIntentId!).metadata = { ...metadata, servicehub_provider_id: other.id };
  await assert.rejects(reconcileSubscriptionPayment(provider.id, checkout.paymentIntentId!), /do not match/);
  intents.get(checkout.paymentIntentId!).metadata = metadata;
  const verified = await reconcileSubscriptionPayment(provider.id, checkout.paymentIntentId!);
  assert.equal(verified.paymentStatus, 'SUCCEEDED');
  assert.equal((await getProviderSubscription(provider.id)).plan, 'PRO');
  assert.ok((await getProviderPaymentRecords(prisma, provider.id, { page: 1, limit: 10, status: 'all' })).summary, 'Pro uses the same analytics');
  const replay = await reconcileSubscriptionPayment(provider.id, checkout.paymentIntentId!);
  assert.equal(replay.subscriptionExpiresAt?.toISOString(), verified.subscriptionExpiresAt?.toISOString(), 'Replay never extends a paid month');
  assert.equal((await prisma.paymentAttempt.findUniqueOrThrow({ where: { id: freeAttempt.id } })).commissionRateBps, 1000, 'Earlier payment snapshots stay unchanged');
  const more = await Promise.all([5, 6, 7, 8].map(i => createService(provider.id, input(i))));
  assert.equal(more.length, 4);
  const proAttempt = await initiateOnlinePayment({ seekerId: customer.id, serviceId: more[0]!.id, paymentMethod: 'gcash', serviceLocationMode: 'REMOTE' });
  assert.equal(proAttempt.commissionRateBps, 500);
  assert.equal(Number(proAttempt.platformFeeAmount), 50);
  assert.equal(Number(proAttempt.providerNetAmount), 950);
  const cancelled = await cancelProviderSubscription(provider.id);
  assert.equal(cancelled.subscriptionStatus, 'CANCELLED'); assert.equal(cancelled.plan, 'PRO');
  await prisma.user.update({ where: { id: provider.id }, data: { subscriptionExpiresAt: new Date(Date.now() - 1) } });
  const expired = await getProviderSubscription(provider.id);
  assert.equal(expired.subscriptionStatus, 'EXPIRED'); assert.equal(expired.plan, 'FREE');
  assert.equal(expired.activeListings, 7, 'Expiry keeps all existing listings');
  await assert.rejects(createService(provider.id, input(9)), /3-service listing limit/);
  await toggleServiceAvailability(more[0]!.id, provider.id);
  await assert.rejects(toggleServiceAvailability(more[0]!.id, provider.id), /3-service listing limit/);
  // Existing provider analytics remain callable on Free, cancelled-Pro and expired-Pro.
  const records = await getProviderPaymentRecords(prisma, provider.id, { page: 1, limit: 10, status: 'all' });
  assert.ok(records.summary);
  const failed = await startSubscriptionCheckout(other.id);
  intents.get(failed.paymentIntentId!).status = 'awaiting_payment_method';
  assert.equal((await reconcileSubscriptionPayment(other.id, failed.paymentIntentId!)).paymentStatus, 'FAILED');
  assert.equal((await getProviderSubscription(other.id)).plan, 'FREE');
  const abandoned = await startSubscriptionCheckout(other.id);
  assert.equal((await cancelSubscriptionCheckout(other.id, abandoned.paymentIntentId!)).paymentStatus, 'CANCELLED');
  assert.equal((await getProviderSubscription(other.id)).plan, 'FREE');
  paid(abandoned.paymentIntentId!);
  assert.equal((await reconcileSubscriptionPayment(other.id, abandoned.paymentIntentId!)).paymentStatus, 'REFUNDED', 'A late charge on cancelled checkout is refunded, not upgraded');
  const timeout = await startSubscriptionCheckout(other.id);
  await prisma.subscriptionPayment.update({ where: { id: timeout.id }, data: { checkoutExpiresAt: new Date(Date.now() - 1) } });
  assert.equal((await reconcileSubscriptionPayment(other.id, timeout.paymentIntentId!)).paymentStatus, 'EXPIRED');
  const overview = await adminSubscriptionOverview(1, 20);
  assert.equal(overview.summary.subscriptionRevenue, 0, 'Test payments never count as real subscription revenue');
  assert.equal(overview.summary.testSubscriptionTotal, 199);
  assert.equal(overview.summary.expiredProSubscriptions, 1);
  const networkProvider = await user('subscriptionnetwork');
  const gatewayFetch = globalThis.fetch;
  globalThis.fetch = (async () => { throw new Error('Simulated network interruption'); }) as typeof fetch;
  await assert.rejects(startSubscriptionCheckout(networkProvider.id), /unavailable/);
  assert.equal((await getProviderSubscription(networkProvider.id)).plan, 'FREE');
  globalThis.fetch = gatewayFetch;
  const recovered = await startSubscriptionCheckout(networkProvider.id);
  assert.equal(await prisma.subscriptionPayment.count({ where: { providerId: networkProvider.id } }), 1, 'Ambiguous network failure retries the same payment, not a duplicate charge');
  assert.equal((await getAccountDeletionEligibility(networkProvider.id)).counts.paymentAttempts, 1, 'Pending subscriptions are included in existing deletion safeguards');
  await cancelSubscriptionCheckout(networkProvider.id, recovered.paymentIntentId!);
  assert.equal((await getAccountDeletionEligibility(networkProvider.id)).eligible, true);
});
